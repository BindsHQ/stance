// Renders raster brand assets from the SVG masters in brand/logo/svg with Chromium,
// then copies the web set into the docs site. Run: node scripts/build-brand.mjs
// PNGs are optimised losslessly afterwards with `oxipng -o max --strip safe` (see brand/README.md).
import { chromium } from '@playwright/test';
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = join(import.meta.dirname, '..');
const svgDir = join(root, 'brand', 'logo', 'svg');
const pngDir = join(root, 'brand', 'logo', 'png');
const favDir = join(root, 'brand', 'favicon');
mkdirSync(pngDir, { recursive: true });
mkdirSync(favDir, { recursive: true });

const svg = (name) => readFileSync(join(svgDir, name), 'utf8');
const jobs = [
  // High-resolution renders of the masters (the supplied originals are kept at 1x).
  ['stance-logo-indigo.svg', join(pngDir, 'stance-logo-indigo@2x.png'), 3364, 752],
  ['stance-logo-ivory.svg', join(pngDir, 'stance-logo-ivory@2x.png'), 3364, 752],
  ['stance-mark-indigo.svg', join(pngDir, 'stance-mark-indigo@2x.png'), 764, 752],
  ['stance-mark-ivory.svg', join(pngDir, 'stance-mark-ivory@2x.png'), 764, 752],
  // App and favicon set: ivory mark on an indigo tile.
  ['stance-favicon.svg', join(favDir, 'favicon-16.png'), 16, 16],
  ['stance-favicon.svg', join(favDir, 'favicon-32.png'), 32, 32],
  ['stance-favicon.svg', join(favDir, 'favicon-48.png'), 48, 48],
  ['stance-app-icon.svg', join(favDir, 'apple-touch-icon.png'), 180, 180, true],
  ['stance-app-icon.svg', join(favDir, 'icon-192.png'), 192, 192],
  ['stance-app-icon.svg', join(favDir, 'icon-512.png'), 512, 512],
  ['stance-app-icon-maskable.svg', join(favDir, 'icon-maskable-512.png'), 512, 512],
];

const copyOnly = process.argv.includes('--copy-only');
if (!copyOnly) {
  const browser = await chromium.launch();
  const page = await browser.newPage({ deviceScaleFactor: 1 });
  for (const [file, out, w, h, opaque] of jobs) {
    let markup = svg(file).replace('<svg ', `<svg width="${w}" height="${h}" `);
    // Apple touch icons must be opaque: iOS fills transparency with black.
    if (opaque) markup = markup.replace(/rx="\d+"/, 'rx="0"');
    await page.setViewportSize({ width: w, height: h });
    await page.setContent(
      `<html><body style="margin:0;background:transparent">${markup}</body></html>`,
    );
    await page.locator('svg').screenshot({ path: out, omitBackground: !opaque });
    console.log('rendered', out.replace(root + '/', ''), `${w}×${h}`);
  }
  await browser.close();
}

// Web set for the docs site.
const pub = join(root, 'apps', 'docs', 'public');
mkdirSync(join(pub, 'brand'), { recursive: true });
copyFileSync(join(svgDir, 'stance-favicon.svg'), join(pub, 'icon.svg'));
for (const f of ['apple-touch-icon.png', 'icon-192.png', 'icon-512.png', 'icon-maskable-512.png'])
  copyFileSync(join(favDir, f), join(pub, f));
for (const f of [
  'stance-logo.svg',
  'stance-logo-indigo.svg',
  'stance-logo-ivory.svg',
  'stance-mark.svg',
  'stance-mark-indigo.svg',
  'stance-mark-ivory.svg',
  'stance-app-icon.svg',
])
  copyFileSync(join(svgDir, f), join(pub, 'brand', f));
for (const f of [
  'stance-logo-indigo.png',
  'stance-logo-ivory.png',
  'stance-logo-indigo@2x.png',
  'stance-logo-ivory@2x.png',
  'stance-mark-indigo.png',
  'stance-mark-ivory.png',
  'stance-mark-indigo@2x.png',
  'stance-mark-ivory@2x.png',
])
  copyFileSync(join(pngDir, f), join(pub, 'brand', f));
// Path data for inline, theme-aware logos in the docs site.
const pathOf = (f) => svg(f).match(/ d="([^"]+)"/)[1];
const viewBoxOf = (f) => svg(f).match(/viewBox="([^"]+)"/)[1];
writeFileSync(
  join(root, 'apps', 'docs', 'components', 'brand-paths.ts'),
  `// Generated by scripts/build-brand.mjs from brand/logo/svg — do not edit.\n` +
    `export const LOGO = { viewBox: '${viewBoxOf('stance-logo.svg')}', d: '${pathOf('stance-logo.svg')}' } as const;\n` +
    `export const MARK = { viewBox: '${viewBoxOf('stance-mark.svg')}', d: '${pathOf('stance-mark.svg')}' } as const;\n`,
);
console.log('copied web set to apps/docs/public and generated brand-paths.ts');
