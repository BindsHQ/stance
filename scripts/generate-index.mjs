// Regenerates packages/react/src/components/index.ts from component folders.
import { existsSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = join(import.meta.dirname, '..', 'packages', 'react', 'src', 'components');
const names = readdirSync(dir, { withFileTypes: true })
  .filter((d) => d.isDirectory() && existsSync(join(dir, d.name, 'index.ts')))
  .map((d) => d.name)
  .sort();
const body = names.map((n) => `export * from './${n}/index.js';`).join('\n');
writeFileSync(
  join(dir, 'index.ts'),
  `// Generated by scripts/generate-index.mjs — do not edit.\n${body}\n`,
);
console.log(`components/index.ts: ${names.length} components`);
