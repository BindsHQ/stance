// Generates Sources/StanceUI/Icons/StanceIconData.swift from the shared Stance icon geometry
// (packages/react/src/icons/paths.ts), so web and iOS draw exactly the same icons.
// Run from the repository root: node platforms/ios/Scripts/generate-icons.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = join(import.meta.dirname, '..', '..', '..');
const src = readFileSync(join(root, 'packages', 'react', 'src', 'icons', 'paths.ts'), 'utf8');
const body = src.slice(src.indexOf('export const iconPaths = {') + 'export const iconPaths = {'.length, src.indexOf('} as const;'));
const icons = [];
for (const m of body.matchAll(/^\s*(?:'([^']+)'|([a-zA-Z0-9_]+)):\s*\[([\s\S]*?)\],?\s*$/gm)) {
  const name = m[1] ?? m[2];
  const paths = [...m[3].matchAll(/'([^']+)'/g)].map((p) => p[1]);
  icons.push({ name, paths });
}
if (icons.length < 50) throw new Error(`Only parsed ${icons.length} icons; the source format may have changed.`);
const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const reserved = new Set(['import', 'default', 'switch', 'case', 'repeat', 'operator', 'self', 'type', 'extension']);
const id = (n) => (reserved.has(camel(n)) ? `\`${camel(n)}\`` : camel(n));
const out = `// Generated by platforms/ios/Scripts/generate-icons.mjs from packages/react/src/icons/paths.ts. Do not edit.
// swiftlint:disable all

/// The Stance icon set. Geometry is shared with the web: a 24pt grid, 1.75 stroke, round caps and joins.
public enum StanceIconName: String, CaseIterable, Sendable {
${icons.map((i) => `    case ${id(i.name)} = "${i.name}"`).join('\n')}

    /// SVG path data for each stroke of the icon.
    var pathData: [String] {
        switch self {
${icons.map((i) => `        case .${id(i.name)}: [${i.paths.map((p) => JSON.stringify(p)).join(', ')}]`).join('\n')}
        }
    }
}
`;
writeFileSync(join(root, 'platforms', 'ios', 'Sources', 'StanceUI', 'Icons', 'StanceIconData.swift'), out);
console.log(`generated ${icons.length} icons`);
