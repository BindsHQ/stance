// Turns every `example` in components.json into compiled Swift, so documented snippets cannot rot.
// Run from the repository root: node platforms/ios/Scripts/generate-example-tests.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = join(import.meta.dirname, '..');
const components = JSON.parse(readFileSync(join(dir, 'components.json'), 'utf8'));
const body = components
  .map((c, i) => {
    const uikit = /StanceUIKit|StanceDocumentPreview/.test(c.example);
    const view = `    /// ${c.name}\n    struct Example${i}: View {\n        @State var text = ""\n        @State var isOn = true\n        @State var value = 50.0\n        @State var date = Date()\n        @State var role = "admin"\n        @State var filters: Set<String> = []\n        @State var signature = StanceSignature()\n        @State var isPresented = false\n        @State var confirmation: StanceConfirmation?\n        var body: some View {\n            ${c.example}\n        }\n    }`;
    return uikit ? `    #if canImport(UIKit)\n${view}\n    #endif` : view;
  })
  .join('\n\n');
writeFileSync(
  join(dir, 'Tests', 'StanceUITests', 'ComponentExamples.swift'),
  `// Generated by platforms/ios/Scripts/generate-example-tests.mjs from components.json. Do not edit.\nimport Foundation\nimport StanceUI\nimport SwiftUI\nimport Testing\n\n/// Compiles every documented example. If this file fails to build, a snippet in components.json is wrong.\n@MainActor\nenum ComponentExamples {\n    struct Named: Identifiable { let name: String; var id: String { name } }\n\n${body}\n}\n\n@Test("components.json lists ${components.length} documented components") func inventoryCount() {\n    #expect(${components.length} > 50)\n}\n`,
);
console.log(`generated ${components.length} compiled examples`);
