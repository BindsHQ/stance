// Generates Compose ImageVectors from the shared Stance icon geometry
// (packages/react/src/icons/paths.ts), so every platform draws the same icons.
// Run from the repository root: node platforms/android/scripts/generate-icons.mjs
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

const root = join(import.meta.dirname, '..', '..', '..');
const source = readFileSync(join(root, 'packages', 'react', 'src', 'icons', 'paths.ts'), 'utf8');
const out = join(root, 'platforms', 'android', 'stance-compose', 'src', 'main', 'kotlin', 'com', 'bindshq', 'stance', 'icons', 'StanceIcons.kt');

const icons = [];
for (const m of source.matchAll(/^\s+(?:'([^']+)'|([a-zA-Z][\w]*)):\s*\[([^\]]*)\]/gm)) {
  const name = m[1] ?? m[2];
  const paths = [...m[3].matchAll(/'([^']+)'/g)].map((p) => p[1]);
  if (paths.length) icons.push({ name, paths });
}
if (icons.length < 50) throw new Error(`Only parsed ${icons.length} icons; the source format may have changed.`);

const pascal = (s) => s.split(/[-_]/).map((p) => p[0].toUpperCase() + p.slice(1)).join('');
const body = icons
  .map(({ name, paths }) => `    /** \`${name}\` */\n    public val ${pascal(name)}: ImageVector by lazy { stanceIcon("${name}", ${paths.map((p) => `"${p}"`).join(', ')}) }`)
  .join('\n\n');

const file = `// Generated by platforms/android/scripts/generate-icons.mjs from packages/react/src/icons/paths.ts. Do not edit.
package com.bindshq.stance.icons

import androidx.compose.ui.graphics.vector.ImageVector

/**
 * The Stance icon set: ${icons.length} icons on a 24dp grid with a 1.75 stroke and round caps and joins.
 * The geometry is shared with the web and iOS implementations.
 */
public object StanceIcons {
${body}

    /** Every icon with its token name, for galleries and tests. */
    public val all: List<Pair<String, ImageVector>> by lazy {
        listOf(
${icons.map(({ name }) => `            "${name}" to ${pascal(name)},`).join('\n')}
        )
    }
}
`;
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, file);
console.log(`generated ${icons.length} icons`);
