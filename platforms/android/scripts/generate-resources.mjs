// Generates Android colour resources for Theme.Stance from the resolved token JSON, so the
// window background shown before Compose draws matches the Stance theme exactly.
// Run from the repository root: node platforms/android/scripts/generate-resources.mjs
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = join(import.meta.dirname, '..', '..', '..');
const tokens = JSON.parse(readFileSync(join(root, 'packages', 'tokens', 'generated', 'json', 'tokens.resolved.json'), 'utf8'));
const res = join(root, 'platforms', 'android', 'stance-compose', 'src', 'main', 'res');
const roles = ['bg-canvas', 'bg-surface', 'fg-default', 'accent-bg', 'accent-fg'];
const header = '<!-- Generated by platforms/android/scripts/generate-resources.mjs from the Stance token source. Do not edit. -->';

const colors = (theme) =>
  `<?xml version="1.0" encoding="utf-8"?>\n${header}\n<resources>\n${roles
    .map((r) => `    <color name="stance_${r.replace(/-/g, '_')}">${tokens.themes[theme][`color.${r}`].value.hex}</color>`)
    .join('\n')}\n</resources>\n`;

for (const [dir, theme] of [['values', 'light'], ['values-night', 'dark']]) {
  mkdirSync(join(res, dir), { recursive: true });
  writeFileSync(join(res, dir, 'stance_colors.xml'), colors(theme));
}
console.log('generated stance_colors.xml for light and night');
