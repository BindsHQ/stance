export function Statuses() {
  const [status, setStatus] = React.useState<GenerationStatus>('submitted');
  return (
    <div style={{ display: 'grid', gap: 12, width: '100%', maxWidth: 520 }}>
      <SummaryCard status={status} points={status === 'submitted' ? undefined : points} />
      <div>
        <Button
          size="sm"
          variant="outline"
          onClick={() => setStatus((s) => (s === 'submitted' ? 'complete' : 'submitted'))}
        >
          {status === 'submitted' ? 'Finish the summary' : 'Summarise again'}
        </Button>
      </div>
    </div>
  );
}

