export function WithStateItems() {
  const [ruler, setRuler] = React.useState(true);
  const [device, setDevice] = React.useState('desktop');
  return (
    <Menubar aria-label="Preview">
      <MenubarMenu>
        <MenubarTrigger>View</MenubarTrigger>
        <MenubarContent>
          <MenubarCheckboxItem checked={ruler} onCheckedChange={setRuler}>
            Show ruler
          </MenubarCheckboxItem>
          <MenubarSeparator />
          <MenubarRadioGroup value={device} onValueChange={setDevice}>
            <MenubarRadioItem value="desktop">Desktop client</MenubarRadioItem>
            <MenubarRadioItem value="mobile">Mobile client</MenubarRadioItem>
            <MenubarRadioItem value="web">Outlook on the web</MenubarRadioItem>
          </MenubarRadioGroup>
        </MenubarContent>
      </MenubarMenu>
    </Menubar>
  );
}

