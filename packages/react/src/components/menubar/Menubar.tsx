interface MenubarContextValue {
  value: string | null;
  setValue: (value: string | null) => void;
  barRef: React.RefObject<HTMLDivElement | null>;
}

const [MenubarProvider, useMenubar] = createStrictContext<MenubarContextValue>('Menubar');

export interface MenubarProps extends Omit<
  React.HTMLAttributes<HTMLDivElement>,
  'defaultValue' | 'onChange'
> {
  /** The open menu's value (controlled). */
  value?: string | null;
  defaultValue?: string | null;
  onValueChange?: (value: string | null) => void;
  /** Wrap keyboard focus between first and last menus. Default true. */
  loop?: boolean;
}

/** A persistent horizontal bar of menus, as in desktop editors (File, Edit, View). */
export const Menubar = React.forwardRef<HTMLDivElement, MenubarProps>(function Menubar(
  {
    value: valueProp,
    defaultValue = null,
    onValueChange,
    loop = true,
    className,
    onKeyDown,
    children,
    ...props
  },
  forwardedRef,
) {
  const [value, setValue] = useControllableState<string | null>({
    value: valueProp,
    defaultValue,
    onChange: onValueChange,
  });
  const barRef = React.useRef<HTMLDivElement>(null);
  const composed = useComposedRefs(forwardedRef, barRef);
  const roving = useRovingFocus(barRef, {
    orientation: 'horizontal',
    loop,
    itemSelector: '[data-menubar-trigger]',
  });
  const ctx = React.useMemo(() => ({ value, setValue, barRef }), [value, setValue]);
  return (
    <MenubarProvider value={ctx}>
      <div
        ref={composed}
        role="menubar"
        aria-orientation="horizontal"
        className={cx('st-menubar', className)}
        onKeyDown={(e) => {
          onKeyDown?.(e);
          // Only handle keys on the triggers themselves, not those bubbling from portalled menus.
          if (!e.defaultPrevented && (e.target as HTMLElement).hasAttribute('data-menubar-trigger'))
            roving.onKeyDown(e);
        }}
        {...props}
      >
        {children}
      </div>
    </MenubarProvider>
  );
});

export interface MenubarMenuProps {
  children?: React.ReactNode;
  /** Identifier for controlled usage. Generated by default. */
  value?: string;
}

/** One top-level menu in the bar. */
export function MenubarMenu({ children, value: valueProp }: MenubarMenuProps) {
  const bar = useMenubar('MenubarMenu');
  const generated = React.useId();
  const value = valueProp ?? generated;
  const open = bar.value === value;
  const { setValue, barRef } = bar;
  const onHorizontalNav = React.useCallback(
    (direction: 1 | -1) => {
      const triggers = Array.from(
        barRef.current?.querySelectorAll<HTMLElement>('[data-menubar-trigger]:not([disabled])') ??
          [],
      );
      const index = triggers.findIndex((t) => t.dataset.value === value);
      if (index < 0 || triggers.length === 0) return;
      const next = triggers[(index + direction + triggers.length) % triggers.length]!;
      next.focus({ preventScroll: true });
      setValue(next.dataset.value ?? null);
    },
    [barRef, setValue, value],
  );
  return (
    <MenuRoot
      open={open}
      onOpenChange={(o) => setValue(o ? value : null)}
      onHorizontalNav={onHorizontalNav}
    >
      <MenubarMenuValue.Provider value={value}>{children}</MenubarMenuValue.Provider>
    </MenuRoot>
  );
}

const MenubarMenuValue = React.createContext<string>('');

export type MenubarTriggerProps = React.ButtonHTMLAttributes<HTMLButtonElement>;

/** The top-level menu button inside the bar. */
export const MenubarTrigger = React.forwardRef<HTMLButtonElement, MenubarTriggerProps>(
  function MenubarTrigger(
    { className, onClick, onKeyDown, onPointerEnter, disabled, ...props },
    ref,
  ) {
    const root = useMenuRoot('MenubarTrigger');
    const bar = useMenubar('MenubarTrigger');
    const value = React.useContext(MenubarMenuValue);
    const composed = useComposedRefs(ref, root.triggerRef as React.Ref<HTMLButtonElement>);
    return (
      <button
        ref={composed}
        type="button"
        role="menuitem"
        id={root.triggerId}
        disabled={disabled}
        aria-haspopup="menu"
        aria-expanded={root.open}
        aria-controls={root.open ? root.contentId : undefined}
        data-state={root.open ? 'open' : 'closed'}
        data-menubar-trigger=""
        data-value={value}
        className={cx('st-menubar__trigger', className)}
        onClick={composeHandlers(onClick, () => {
          root.focusIntentRef.current = 'first';
          root.setOpen(!root.open);
        })}
        onKeyDown={composeHandlers(onKeyDown, (e: React.KeyboardEvent) => {
          if (e.key === 'ArrowDown' || e.key === 'ArrowUp') {
            e.preventDefault();
            root.focusIntentRef.current = e.key === 'ArrowUp' ? 'last' : 'first';
            root.setOpen(true);
          }
        })}
        onPointerEnter={composeHandlers(onPointerEnter, (e: React.PointerEvent) => {
          // Moving across the bar while a menu is open switches menus, as in native menubars.
          if (e.pointerType === 'mouse' && bar.value !== null && bar.value !== value && !disabled) {
            root.focusIntentRef.current = 'none';
            (e.currentTarget as HTMLElement).focus({ preventScroll: true });
            bar.setValue(value);
          }
        })}
        {...props}
      />
    );
  },
);

export const MenubarContent = React.forwardRef<HTMLDivElement, MenuContentProps>(
  function MenubarContent({ align = 'start', sideOffset = 6, ...props }, ref) {
    return <MenuContent ref={ref} side="bottom" align={align} sideOffset={sideOffset} {...props} />;
  },
);

