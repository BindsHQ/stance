import { render, screen } from '@testing-library/react';
import * as React from 'react';
import { describe, expect, it } from 'vitest';
import { expectNoA11yViolations, THEMES } from '../../../test/a11y';
import { AIGeneratedLabel } from './AIGeneratedLabel';

describe('AIGeneratedLabel', () => {
  it('says the content was generated by AI by default, beside a decorative sparkle', () => {
    const { container } = render(<AIGeneratedLabel />);
    expect(screen.getByText('Generated by AI')).toBeInTheDocument();
    const icon = container.querySelector('svg')!;
    expect(icon).toHaveAttribute('data-icon', 'sparkle');
    expect(icon).toHaveAttribute('aria-hidden', 'true');
  });

  it.each([
    ['generated', 'Generated by AI'],
    ['assisted', 'Written with AI'],
    ['edited', 'Edited by AI'],
  ] as const)('uses its own words for the %s variant', (variant, text) => {
    const { container } = render(<AIGeneratedLabel variant={variant} />);
    expect(screen.getByText(text)).toBeInTheDocument();
    expect(container.firstElementChild).toHaveAttribute('data-variant', variant);
  });

  it('adds the model name in words', () => {
    render(<AIGeneratedLabel model="Atlas 2" />);
    expect(screen.getByText('Generated by AI with Atlas 2')).toBeInTheDocument();
  });

  it('accepts a label override, translations and a custom model template', () => {
    const { rerender } = render(<AIGeneratedLabel label="Drafted by the assistant" />);
    expect(screen.getByText('Drafted by the assistant')).toBeInTheDocument();
    rerender(
      <AIGeneratedLabel
        variant="edited"
        model="Atlas 2"
        labels={{ edited: 'Uredil UI', withModel: (l, m) => `${l} (${m})` }}
      />,
    );
    expect(screen.getByText('Uredil UI (Atlas 2)')).toBeInTheDocument();
    rerender(<AIGeneratedLabel label={<em>Summary by AI</em>} model="Atlas 2" />);
    expect(screen.getByText('Summary by AI').parentElement).toHaveTextContent(
      'Summary by AI · Atlas 2',
    );
  });

  it('can hide the icon and passes size, className, rest props and the ref', () => {
    const ref = React.createRef<HTMLSpanElement>();
    const { container } = render(
      <AIGeneratedLabel
        ref={ref}
        showIcon={false}
        size="sm"
        className="custom"
        data-testid="label"
      />,
    );
    const label = screen.getByTestId('label');
    expect(container.querySelector('svg')).toBeNull();
    expect(ref.current).toBe(label);
    expect(label).toHaveClass('st-ai-generated-label', 'custom');
    expect(label).toHaveAttribute('data-size', 'sm');
  });

  it.each(THEMES)('has no axe violations in %s', async (theme) => {
    const { container } = render(
      <div data-theme={theme}>
        <AIGeneratedLabel />
        <AIGeneratedLabel variant="assisted" size="sm" model="Atlas 2" />
      </div>,
    );
    await expectNoA11yViolations(container);
  });
});
