'use client';
import * as React from 'react';
import { cx } from '../../internal/cx.js';
import type { GenerationStatus } from '../../internal/generation-status.js';
import { useAnnouncer } from '../../internal/use-announcer.js';
import { Icon } from '../../icons/Icon.js';
import { AIGeneratedLabel } from '../ai-generated-label/AIGeneratedLabel.js';
import { EmptyState } from '../empty-state/EmptyState.js';
import { Skeleton } from '../skeleton/Skeleton.js';

export interface SemanticSearchResult {
  /** Stable id. */
  id: string;
  /** The title of the result. */
  title: string;
  /** Where the result opens. Without it the title is a button. */
  href?: string;
  /** The passage that matched. */
  snippet: string;
  /** Words or phrases in the snippet to mark as the match. */
  highlights?: string[];
  /** Where the result comes from, for example a site, a folder or a document type. */
  source?: string;
  /** How close the match is, from 0 to 1. Shown as a percentage in words. */
  score?: number;
  /** One line on why this result matched. */
  reason?: string;
}

export interface SemanticSearchResultsLabels {
  /** Accessible name of the section. Default "Search results". */
  label: string;
  /** The count line, also announced when loading ends. Default "3 results for query". */
  count: (count: number, query: string | undefined) => string;
  /** Read by screen readers while searching. Default "Searching". */
  loading: string;
  /** Heading of the AI answer. Default "Answer". */
  answer: string;
  /** The words of the generated label on the answer. Default "Generated by AI". */
  generated: string;
  /** Title of the empty state. Default "No results". */
  emptyTitle: string;
  /** Description of the empty state. Default "Try other words or a broader question." */
  emptyDescription: (query: string | undefined) => string;
  /** Shown when the search failed. Default "The search could not be completed". */
  error: string;
  /** Hidden text before the reason. Default "Why it matched". */
  reason: string;
  /** Formats the score. Default "92% match". */
  score: (score: number) => string;
}

export interface SemanticSearchResultsProps extends Omit<
  React.HTMLAttributes<HTMLElement>,
  'results'
> {
  /** The query the results belong to. Used in the count line. */
  query?: string;
  /** An AI answer shown above the results. */
  answer?: React.ReactNode;
  /** The results, best match first. */
  results: SemanticSearchResult[];
  /** `submitted` and `streaming` show the loading state. Default `complete`. */
  status?: GenerationStatus;
  /** Called when the reader opens a result. */
  onResultSelect?: (result: SemanticSearchResult) => void;
  /** Replaces the built in empty state. */
  emptyState?: React.ReactNode;
  /** Link target for results with `href`. */
  target?: React.HTMLAttributeAnchorTarget;
  /** Heading level of result titles. The answer heading uses the same level. Default 3. */
  headingLevel?: 2 | 3 | 4 | 5 | 6;
  /** How many placeholders to show while loading. Default 3. */
  loadingCount?: number;
  /** Translations for the built in strings. */
  labels?: Partial<SemanticSearchResultsLabels>;
}

const escapeRegExp = (value: string) => value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

/** Splits a snippet into plain and matching parts. Longer phrases win over the words inside them. */
export function splitHighlights(
  snippet: string,
  highlights: string[] | undefined,
): { text: string; match: boolean }[] {
  const terms = (highlights ?? [])
    .map((term) => term.trim())
    .filter(Boolean)
    .sort((a, b) => b.length - a.length);
  if (terms.length === 0 || !snippet) return [{ text: snippet, match: false }];
  const pattern = new RegExp(`(${terms.map(escapeRegExp).join('|')})`, 'gi');
  const wanted = new Set(terms.map((term) => term.toLowerCase()));
  return snippet
    .split(pattern)
    .filter((part) => part !== '')
    .map((part) => ({ text: part, match: wanted.has(part.toLowerCase()) }));
}

/**
 * Search results ranked by meaning. Each result shows the passage that matched, with the
 * match marked, and why it matched, under an optional AI answer.
 */
export const SemanticSearchResults = React.forwardRef<HTMLElement, SemanticSearchResultsProps>(
  function SemanticSearchResults(
    {
      query,
      answer,
      results,
      status = 'complete',
      onResultSelect,
      emptyState,
      target,
      headingLevel = 3,
      loadingCount = 3,
      labels: labelsProp,
      className,
      ...props
    },
    ref,
  ) {
    const labels: SemanticSearchResultsLabels = {
      label: 'Search results',
      count: (count, q) => {
        const base = count === 1 ? '1 result' : `${count} results`;
        return q ? `${base} for ${q}` : base;
      },
      loading: 'Searching',
      answer: 'Answer',
      generated: 'Generated by AI',
      emptyTitle: 'No results',
      emptyDescription: () => 'Try other words or a broader question.',
      error: 'The search could not be completed',
      reason: 'Why it matched',
      score: (score) => `${Math.round(Math.min(1, Math.max(0, score)) * 100)}% match`,
      ...labelsProp,
    };
    const Heading = `h${headingLevel}` as 'h3';
    const answerId = React.useId();
    const loading = status === 'submitted' || status === 'streaming';
    const failed = status === 'error';
    const countText = labels.count(results.length, query);

    // The count is announced once, when loading ends.
    const { announce, region } = useAnnouncer();
    const wasLoading = React.useRef(loading);
    const countRef = React.useRef(countText);
    countRef.current = countText;
    React.useEffect(() => {
      if (wasLoading.current && !loading && status !== 'error') announce(countRef.current);
      wasLoading.current = loading;
    }, [loading, status, announce]);

    return (
      <section
        ref={ref}
        aria-label={labels.label}
        aria-busy={loading || undefined}
        className={cx('st-semantic-search-results', className)}
        data-status={status}
        {...props}
      >
        {answer != null && (
          <div
            className="st-semantic-search-results__answer"
            role="group"
            aria-labelledby={answerId}
          >
            <div className="st-semantic-search-results__answer-header">
              <Heading id={answerId} className="st-semantic-search-results__answer-title">
                {labels.answer}
              </Heading>
              <AIGeneratedLabel size="sm" label={labels.generated} />
            </div>
            <div className="st-semantic-search-results__answer-body">{answer}</div>
          </div>
        )}
        {loading ? (
          <div className="st-semantic-search-results__loading">
            <span className="st-sr-only">{labels.loading}</span>
            {Array.from({ length: Math.max(1, loadingCount) }, (_, i) => (
              <div key={i} className="st-semantic-search-results__placeholder" aria-hidden="true">
                <Skeleton width="45%" />
                <Skeleton lines={2} />
              </div>
            ))}
          </div>
        ) : failed ? (
          <p className="st-semantic-search-results__error" role="alert">
            <Icon name="alert-circle" size={16} />
            <span>{labels.error}</span>
          </p>
        ) : results.length === 0 ? (
          (emptyState ?? (
            <EmptyState
              size="sm"
              icon={<Icon name="search" size="lg" />}
              title={labels.emptyTitle}
              description={labels.emptyDescription(query)}
              headingLevel={headingLevel}
            />
          ))
        ) : (
          <>
            <p className="st-semantic-search-results__count">{countText}</p>
            <ol className="st-semantic-search-results__list">
              {results.map((result) => {
                const select = () => onResultSelect?.(result);
                return (
                  <li key={result.id} className="st-semantic-search-results__item">
                    <div className="st-semantic-search-results__item-header">
                      <Heading className="st-semantic-search-results__title">
                        {result.href ? (
                          <a
                            className="st-semantic-search-results__link"
                            href={result.href}
                            target={target}
                            rel={target === '_blank' ? 'noopener noreferrer' : undefined}
                            onClick={select}
                          >
                            {result.title}
                          </a>
                        ) : (
                          <button
                            type="button"
                            className="st-semantic-search-results__link"
                            onClick={select}
                          >
                            {result.title}
                          </button>
                        )}
                      </Heading>
                      {result.score !== undefined && (
                        <span className="st-semantic-search-results__score">
                          {labels.score(result.score)}
                        </span>
                      )}
                    </div>
                    {result.source && (
                      <p className="st-semantic-search-results__source">{result.source}</p>
                    )}
                    <p className="st-semantic-search-results__snippet">
                      {splitHighlights(result.snippet, result.highlights).map((part, i) =>
                        part.match ? (
                          <mark key={i} className="st-semantic-search-results__mark">
                            {part.text}
                          </mark>
                        ) : (
                          <React.Fragment key={i}>{part.text}</React.Fragment>
                        ),
                      )}
                    </p>
                    {result.reason && (
                      <p className="st-semantic-search-results__reason">
                        <Icon name="sparkle" size={12} />
                        <span>
                          <span className="st-sr-only">{labels.reason}: </span>
                          {result.reason}
                        </span>
                      </p>
                    )}
                  </li>
                );
              })}
            </ol>
          </>
        )}
        {region}
      </section>
    );
  },
);
