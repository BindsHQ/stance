'use client';
import * as React from 'react';
import { cx } from '../../internal/cx.js';
import type { GenerationStatus } from '../../internal/generation-status.js';
import { formatRelativeTime } from '../../internal/relative-time.js';
import { useAnnouncer } from '../../internal/use-announcer.js';
import { useControllableState } from '../../internal/use-controllable-state.js';
import { Icon } from '../../icons/Icon.js';
import { AIGeneratedLabel } from '../ai-generated-label/AIGeneratedLabel.js';
import { Button } from '../button/Button.js';
import { IconButton } from '../icon-button/IconButton.js';
import { Skeleton } from '../skeleton/Skeleton.js';
import { SourceList, type SourceListItem } from '../source-list/SourceList.js';

export interface SummaryCardLabels {
  /** The title when none is given. Default "Summary". */
  title: string;
  /** The words of the generated label. Default "Generated by AI". */
  generated: string;
  /** Read by screen readers while the summary is being written. Default "Summarising". */
  loading: string;
  /** Announced when the summary is ready. Default "Summary ready". */
  ready: string;
  /** Shown when the summary was stopped early. Default "Summary stopped early". */
  stopped: string;
  /** Shown when the summary failed. Default "The summary could not be created". */
  error: string;
  /** Accessible name of the regenerate button. Default "Regenerate summary". */
  regenerate: string;
  /** The button that opens the original. Default "View original". */
  expand: string;
  /** Accessible name of the collapse control when open. Default "Hide summary". */
  collapse: string;
  /** Accessible name of the collapse control when closed. Default "Show summary". */
  show: string;
  /** Builds the updated note from a relative time. Default "Updated 5 minutes ago". */
  updated: (relative: string) => string;
  /** Heading of the sources. Default "Sources". */
  sources: string;
}

export interface SummaryCardProps extends Omit<React.HTMLAttributes<HTMLElement>, 'title'> {
  /** The title. Default "Summary". */
  title?: React.ReactNode;
  /** The summary as free content. Use this or `points`. */
  children?: React.ReactNode;
  /** The key points, one short sentence each. */
  points?: string[];
  /** Where the summary is in its life cycle. Default `complete`. */
  status?: GenerationStatus;
  /** The sources the summary draws on. */
  sources?: SourceListItem[];
  /** When the summary was last written. A date shows as relative time; other text shows as given. */
  updatedAt?: Date | number | string;
  /** Called when the reader asks for a new summary. Shows a regenerate button. */
  onRegenerate?: () => void;
  /** Called when the reader asks for the original. Shows a button. */
  onExpand?: () => void;
  /** Let the reader fold the summary away. Default false. */
  collapsible?: boolean;
  /** Controlled open state when collapsible. */
  open?: boolean;
  /** Open on first render when collapsible. Default true. */
  defaultOpen?: boolean;
  /** Called when the reader folds or unfolds the summary. */
  onOpenChange?: (open: boolean) => void;
  /** Heading level of the title. Default 3. */
  headingLevel?: 2 | 3 | 4 | 5 | 6;
  /** Translations for the built in strings. */
  labels?: Partial<SummaryCardLabels>;
}

function describeUpdated(value: Date | number | string): { text: string; iso?: string } {
  if (typeof value === 'string') {
    const parsed = /^\d{4}-\d{2}-\d{2}/.test(value) ? new Date(value) : null;
    if (!parsed || Number.isNaN(parsed.getTime())) return { text: value };
    return { text: formatRelativeTime(parsed), iso: parsed.toISOString() };
  }
  const date = value instanceof Date ? value : new Date(value);
  if (Number.isNaN(date.getTime())) return { text: '' };
  return { text: formatRelativeTime(date), iso: date.toISOString() };
}

/**
 * An AI summary of a longer item: key points, a label that says it was generated,
 * the sources behind it and a way back to the original.
 */
export const SummaryCard = React.forwardRef<HTMLElement, SummaryCardProps>(function SummaryCard(
  {
    title,
    children,
    points,
    status = 'complete',
    sources,
    updatedAt,
    onRegenerate,
    onExpand,
    collapsible = false,
    open: openProp,
    defaultOpen = true,
    onOpenChange,
    headingLevel = 3,
    labels: labelsProp,
    className,
    ...props
  },
  ref,
) {
  const labels: SummaryCardLabels = {
    title: 'Summary',
    generated: 'Generated by AI',
    loading: 'Summarising',
    ready: 'Summary ready',
    stopped: 'Summary stopped early',
    error: 'The summary could not be created',
    regenerate: 'Regenerate summary',
    expand: 'View original',
    collapse: 'Hide summary',
    show: 'Show summary',
    updated: (relative) => `Updated ${relative}`,
    sources: 'Sources',
    ...labelsProp,
  };
  const titleId = React.useId();
  const bodyId = React.useId();
  const Heading = `h${headingLevel}` as 'h3';
  const [open, setOpen] = useControllableState({
    value: collapsible ? openProp : undefined,
    defaultValue: defaultOpen,
    onChange: onOpenChange,
  });
  const expanded = !collapsible || open;
  const pending = status === 'submitted';
  const busy = pending || status === 'streaming';
  const hasContent = (points?.length ?? 0) > 0 || children != null;
  const updated = updatedAt !== undefined ? describeUpdated(updatedAt) : null;

  const { announce, region } = useAnnouncer();
  const previous = React.useRef(status);
  const readyRef = React.useRef(labels.ready);
  readyRef.current = labels.ready;
  React.useEffect(() => {
    const was = previous.current;
    previous.current = status;
    if (status === 'complete' && (was === 'submitted' || was === 'streaming'))
      announce(readyRef.current);
  }, [status, announce]);

  return (
    <section
      ref={ref}
      aria-labelledby={titleId}
      className={cx('st-summary-card', className)}
      data-status={status}
      data-state={expanded ? 'open' : 'closed'}
      {...props}
    >
      <div className="st-summary-card__header">
        <div className="st-summary-card__heading">
          <Heading id={titleId} className="st-summary-card__title">
            {title ?? labels.title}
          </Heading>
          <AIGeneratedLabel size="sm" label={labels.generated} />
        </div>
        <div className="st-summary-card__tools">
          {onRegenerate && (
            <IconButton
              label={labels.regenerate}
              icon={<Icon name="refresh" />}
              size="xs"
              disabled={busy}
              onClick={onRegenerate}
            />
          )}
          {collapsible && (
            <IconButton
              label={expanded ? labels.collapse : labels.show}
              icon={<Icon name={expanded ? 'chevron-up' : 'chevron-down'} />}
              size="xs"
              aria-expanded={expanded}
              aria-controls={bodyId}
              onClick={() => setOpen(!expanded)}
            />
          )}
        </div>
      </div>
      <div id={bodyId} className="st-summary-card__body" hidden={!expanded}>
        <div className="st-summary-card__content" aria-busy={busy || undefined}>
          {pending && !hasContent ? (
            <>
              <span className="st-sr-only">{labels.loading}</span>
              <Skeleton lines={3} />
            </>
          ) : (
            <>
              {points && points.length > 0 && (
                <ul className="st-summary-card__points">
                  {points.map((point, i) => (
                    <li key={i}>{point}</li>
                  ))}
                </ul>
              )}
              {children}
            </>
          )}
        </div>
        {status === 'error' && (
          <p className="st-summary-card__note" data-tone="danger" role="alert">
            <Icon name="alert-circle" size={14} />
            <span>{labels.error}</span>
          </p>
        )}
        {status === 'stopped' && (
          <p className="st-summary-card__note">
            <Icon name="stop" size={14} />
            <span>{labels.stopped}</span>
          </p>
        )}
        {sources && sources.length > 0 && (
          <SourceList sources={sources} labels={{ title: labels.sources }} />
        )}
        {(updated?.text || onExpand) && (
          <div className="st-summary-card__footer">
            {updated?.text ? (
              <span className="st-summary-card__updated">
                {updated.iso ? (
                  <time dateTime={updated.iso}>{labels.updated(updated.text)}</time>
                ) : (
                  labels.updated(updated.text)
                )}
              </span>
            ) : (
              <span />
            )}
            {onExpand && (
              <Button
                variant="ghost"
                size="xs"
                trailingIcon={
                  <Icon name="arrow-right" size={14} className="st-summary-card__arrow" />
                }
                onClick={onExpand}
              >
                {labels.expand}
              </Button>
            )}
          </div>
        )}
      </div>
      {region}
    </section>
  );
});
