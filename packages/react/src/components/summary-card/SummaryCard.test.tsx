import { render, screen, within } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import * as React from 'react';
import { describe, expect, it, vi } from 'vitest';
import { expectNoA11yViolations, THEMES } from '../../../test/a11y';
import { SummaryCard } from './SummaryCard';

const points = ['The term ends on 30 June 2027.', 'Notice is 90 days.', 'Renewal is yearly.'];
const sources = [
  { id: 'a', title: 'Master agreement', url: 'https://example.com/agreement' },
  { id: 'b', title: 'Amendment 2', url: 'https://example.com/amendment' },
];
const announcer = (container: HTMLElement) => container.querySelector('[data-st-announcer]')!;

describe('SummaryCard', () => {
  it('is a region named by its title, with a generated label and the points', () => {
    render(<SummaryCard points={points} />);
    const card = screen.getByRole('region', { name: 'Summary' });
    expect(within(card).getByRole('heading', { level: 3, name: 'Summary' })).toBeInTheDocument();
    expect(within(card).getByText('Generated by AI')).toBeVisible();
    expect(within(card).getAllByRole('listitem')).toHaveLength(3);
    expect(card).toHaveAttribute('data-status', 'complete');
  });

  it('renders children, a custom title and heading level', () => {
    render(
      <SummaryCard title="Contract summary" headingLevel={2}>
        <p>Two renewal clauses apply.</p>
      </SummaryCard>,
    );
    expect(screen.getByRole('heading', { level: 2, name: 'Contract summary' })).toBeInTheDocument();
    expect(screen.getByText('Two renewal clauses apply.')).toBeVisible();
  });

  it('shows a placeholder while submitted and announces once when ready', () => {
    const { rerender, container } = render(<SummaryCard status="submitted" />);
    expect(screen.getByText('Summarising')).toBeInTheDocument();
    expect(container.querySelector('.st-summary-card__content')).toHaveAttribute(
      'aria-busy',
      'true',
    );
    expect(announcer(container)).toBeEmptyDOMElement();
    rerender(<SummaryCard status="streaming" points={points.slice(0, 1)} />);
    expect(screen.getAllByRole('listitem')).toHaveLength(1);
    expect(announcer(container)).toBeEmptyDOMElement();
    rerender(<SummaryCard status="complete" points={points} />);
    expect(announcer(container)).toHaveTextContent('Summary ready');
    expect(container.querySelector('.st-summary-card__content')).not.toHaveAttribute('aria-busy');
  });

  it('states errors and early stops in words', () => {
    const { rerender } = render(<SummaryCard status="error" />);
    expect(screen.getByRole('alert')).toHaveTextContent('The summary could not be created');
    rerender(<SummaryCard status="stopped" points={points} />);
    expect(screen.getByText('Summary stopped early')).toBeVisible();
  });

  it('offers regenerate and the original', async () => {
    const user = userEvent.setup();
    const onRegenerate = vi.fn();
    const onExpand = vi.fn();
    const { rerender } = render(
      <SummaryCard points={points} onRegenerate={onRegenerate} onExpand={onExpand} />,
    );
    await user.click(screen.getByRole('button', { name: 'Regenerate summary' }));
    await user.click(screen.getByRole('button', { name: 'View original' }));
    expect(onRegenerate).toHaveBeenCalledTimes(1);
    expect(onExpand).toHaveBeenCalledTimes(1);
    rerender(<SummaryCard status="streaming" points={points} onRegenerate={onRegenerate} />);
    expect(screen.getByRole('button', { name: 'Regenerate summary' })).toBeDisabled();
  });

  it('lists sources and the time it was updated', () => {
    const { rerender } = render(
      <SummaryCard
        points={points}
        sources={sources}
        updatedAt={new Date(Date.now() - 5 * 60000)}
      />,
    );
    expect(screen.getByText('Sources')).toBeInTheDocument();
    const time = screen.getByText('Updated 5 minutes ago');
    expect(time.tagName).toBe('TIME');
    expect(time).toHaveAttribute('datetime');
    rerender(<SummaryCard points={points} updatedAt="this morning" />);
    expect(screen.getByText('Updated this morning')).toBeVisible();
  });

  it('collapses and expands, uncontrolled, with the keyboard', async () => {
    const user = userEvent.setup();
    const onOpenChange = vi.fn();
    render(<SummaryCard points={points} collapsible onOpenChange={onOpenChange} />);
    const toggle = screen.getByRole('button', { name: 'Hide summary' });
    expect(toggle).toHaveAttribute('aria-expanded', 'true');
    toggle.focus();
    await user.keyboard('{Enter}');
    expect(onOpenChange).toHaveBeenLastCalledWith(false);
    expect(screen.getByRole('button', { name: 'Show summary' })).toHaveAttribute(
      'aria-expanded',
      'false',
    );
    expect(screen.getByText(points[0]!)).not.toBeVisible();
    await user.keyboard(' ');
    expect(screen.getByText(points[0]!)).toBeVisible();
  });

  it('supports controlled and default open state', async () => {
    const onOpenChange = vi.fn();
    const { rerender } = render(
      <SummaryCard points={points} collapsible open={false} onOpenChange={onOpenChange} />,
    );
    expect(screen.getByText(points[0]!)).not.toBeVisible();
    await userEvent.click(screen.getByRole('button', { name: 'Show summary' }));
    expect(onOpenChange).toHaveBeenCalledWith(true);
    expect(screen.getByText(points[0]!)).not.toBeVisible();
    rerender(<SummaryCard points={points} collapsible open onOpenChange={onOpenChange} />);
    expect(screen.getByText(points[0]!)).toBeVisible();
    rerender(<SummaryCard key="b" points={points} collapsible defaultOpen={false} />);
    expect(screen.getByText(points[0]!)).not.toBeVisible();
  });

  it('honours translated labels', () => {
    render(
      <SummaryCard
        points={points}
        onExpand={() => {}}
        labels={{ title: 'Sammanfattning', generated: 'Skapad av AI', expand: 'Visa original' }}
      />,
    );
    expect(screen.getByRole('region', { name: 'Sammanfattning' })).toBeInTheDocument();
    expect(screen.getByText('Skapad av AI')).toBeVisible();
    expect(screen.getByRole('button', { name: 'Visa original' })).toBeInTheDocument();
  });

  it('forwards the ref, className and props', () => {
    const ref = React.createRef<HTMLElement>();
    render(<SummaryCard ref={ref} className="mine" id="sum" points={points} />);
    expect(ref.current).toHaveClass('st-summary-card', 'mine');
    expect(ref.current).toHaveAttribute('id', 'sum');
  });

  it.each(THEMES)('has no axe violations in %s', async (theme) => {
    const { container } = render(
      <div data-theme={theme}>
        <SummaryCard
          points={points}
          sources={sources}
          updatedAt={new Date()}
          collapsible
          onRegenerate={() => {}}
          onExpand={() => {}}
        />
        <SummaryCard title="Thread summary" status="submitted" />
        <SummaryCard title="Failed summary" status="error" />
      </div>,
    );
    await expectNoA11yViolations(container);
  });
});
