// ───────────────────────── load ─────────────────────────
const walk = (d) =>
  readdirSync(d).flatMap((f) => {
    const p = join(d, f);
    return statSync(p).isDirectory() ? walk(p) : p.endsWith('.json') ? [p] : [];
  });
const read = (f) => JSON.parse(readFileSync(f, 'utf8'));
const merge = (a, b) => {
  for (const [k, v] of Object.entries(b)) {
    if (v && typeof v === 'object' && !Array.isArray(v) && a[k] && typeof a[k] === 'object')
      merge(a[k], v);
    else a[k] = v;
  }
  return a;
};

const base = {};
const themeFiles = [];
for (const file of walk(sourceDir).sort()) {
  if (file.includes(`${join('source', 'semantic')}`)) themeFiles.push(file);
  else merge(base, read(file));
}

// ───────────────────────── validate + resolve ─────────────────────────
const errors = [];
const TYPES = new Set([
  'color',
  'dimension',
  'fontFamily',
  'fontWeight',
  'number',
  'duration',
  'cubicBezier',
  'shadow',
]);
const isToken = (n) => n && typeof n === 'object' && '$value' in n;

function lookup(root, path) {
  let node = root;
  for (const part of path.split('.')) node = node?.[part];
  return node;
}
function resolve(value, roots, seen = []) {
  if (typeof value === 'string' && /^\{[^}]+\}$/.test(value)) {
    const path = value.slice(1, -1);
    if (seen.includes(path)) throw new Error(`circular alias: ${[...seen, path].join(' → ')}`);
    const target = roots.map((r) => lookup(r, path)).find(isToken);
    if (!target) throw new Error(`unresolved alias ${value}`);
    return resolve(target.$value, roots, [...seen, path]);
  }
  return value;
}
function validateValue(type, v, where) {
  const bad = (m) => errors.push(`${where}: ${m}`);
  const isDim = (d) => d && typeof d.value === 'number' && ['px', 'rem', 'em'].includes(d.unit);
  const isColor = (c) =>
    c &&
    c.colorSpace === 'srgb' &&
    Array.isArray(c.components) &&
    c.components.length === 3 &&
    /^#[0-9A-F]{6}$/.test(c.hex) &&
    typeof c.alpha === 'number';
  switch (type) {
    case 'color':
      if (!isColor(v)) bad('invalid color');
      break;
    case 'dimension':
      if (!isDim(v)) bad('invalid dimension');
      break;
    case 'duration':
      if (!(v && typeof v.value === 'number' && v.unit === 'ms')) bad('invalid duration');
      break;
    case 'cubicBezier':
      if (!(Array.isArray(v) && v.length === 4 && v.every((n) => typeof n === 'number')))
        bad('invalid cubicBezier');
      break;
    case 'fontWeight':
    case 'number':
      if (typeof v !== 'number') bad(`invalid ${type}`);
      break;
    case 'fontFamily':
      if (!(Array.isArray(v) && v.every((s) => typeof s === 'string'))) bad('invalid fontFamily');
      break;
    case 'shadow':
      if (!(
        Array.isArray(v) &&
        v.every((l) => isColor(l.color) && [l.offsetX, l.offsetY, l.blur, l.spread].every(isDim))
      ))
        bad('invalid shadow');
      break;
    default:
      bad(`unknown $type ${type}`);
  }
}
/** Walks a tree, returning { 'a.b.c': { type, value, description, extensions } } with aliases resolved. */
function flatten(tree, roots, prefix = '', inherited, out = {}) {
  for (const [key, node] of Object.entries(tree)) {
    if (key.startsWith('$')) continue;
    const path = prefix ? `${prefix}.${key}` : key;
    const type = node.$type ?? inherited;
    if (isToken(node)) {
      if (!type || !TYPES.has(type)) errors.push(`${path}: missing or unknown $type`);
      let value;
      try {
        value = resolve(node.$value, roots);
      } catch (e) {
        errors.push(`${path}: ${e.message}`);
        continue;
      }
      validateValue(type, value, path);
      out[path] = {
        type,
        value,
        alias: typeof node.$value === 'string' ? node.$value : undefined,
        description: node.$description,
        extensions: node.$extensions,
      };
    } else if (node && typeof node === 'object') {
      flatten(node, roots, path, type, out);
    }
  }
  return out;
}

const primitives = flatten(base, [base]);
const themes = themeFiles.map((file) => {
  const tree = read(file);
  const meta = tree.$extensions?.['com.bindshq.stance'];
  if (!meta?.name) errors.push(`${file}: missing com.bindshq.stance theme metadata`);
  return { ...meta, tokens: flatten(tree, [tree, base]) };
});
const order = ['light', 'dark', 'high-contrast'];
themes.sort((a, b) => order.indexOf(a.name) - order.indexOf(b.name));

// Every theme must define exactly the same roles.
const roleSet = (t) => Object.keys(t.tokens).sort().join('|');
for (const t of themes)
  if (roleSet(t) !== roleSet(themes[0]))
    errors.push(`theme ${t.name} does not define the same roles as ${themes[0].name}`);
// Brand is non-negotiable.
if (primitives['color.brand.ivory']?.value.hex !== '#FCF6EB')
  errors.push('color.brand.ivory must be #FCF6EB');
if (primitives['color.brand.indigo']?.value.hex !== '#140C2E')
  errors.push('color.brand.indigo must be #140C2E');

if (errors.length) {
  console.error(`Token source invalid:\n  ${errors.join('\n  ')}`);
  process.exit(1);
}

// ───────────────────────── brand recipe ─────────────────────────
// The token source says how every colour role derives from a brand (specs/brand-theming.md):
// aliases to the brand pair and the ink scale, plus `com.bindshq.stance.derive` extensions for
// the values that are literal in the source but come from the brand pair. The build turns that
// into one recipe, checks that the Binds pair reproduces every published value, and emits the
// recipe for the web (src/generated.ts), iOS and Android.
const DERIVE = 'com.bindshq.stance.derive';
const BINDS = { name: 'Binds', light: '#FCF6EB', dark: '#140C2E' };
/** Reference brands for the shared cross platform fixture. Chosen to exercise the algorithm. */
const REFERENCE_BRANDS = [
  BINDS,
  { name: 'Harbour', light: '#F2F8FF', dark: '#0A1A50', accent: '#FF5A36' },
  {
    name: 'Sage',
    light: '#F4F2EC',
    dark: '#171D1A',
    accent: { light: '#5E7361', dark: '#8FA892' },
  },
  { name: 'Graphite', light: '#FAFAF7', dark: '#1A1A1F', accent: '#7A7A7A' },
];
const brandErrors = [];
const recipe = (() => {
  const ink = Object.entries(primitives)
    .filter(([p]) => p.startsWith('color.ink.'))
    .map(([p, t]) => {
      const rule = t.extensions?.[DERIVE];
      if (
        !rule ||
        rule.from !== 'light' ||
        rule.toward !== 'dark' ||
        typeof rule.amount !== 'number'
      )
        brandErrors.push(`${p}: needs ${DERIVE} { from: light, toward: dark, amount }`);
      return { step: p.slice('color.ink.'.length), t: rule?.amount ?? 0 };
    });
  const baseRecipe = (path, tok) => {
    if (tok.alias === '{color.brand.ivory}') return { kind: 'light' };
    if (tok.alias === '{color.brand.indigo}') return { kind: 'dark' };
    const inkStep = tok.alias?.match(/^\{color\.ink\.(\d+)\}$/);
    if (inkStep) return { kind: 'ink', step: inkStep[1] };
    if (tok.alias && !tok.alias.startsWith('{color.status.'))
      brandErrors.push(`${path}: alias ${tok.alias} has no brand meaning`);
    return { kind: 'literal', hex: tok.value.hex, alpha: tok.value.alpha };
  };
  const roleRecipe = (theme, path, tok) => {
    const rule = tok.extensions?.[DERIVE];
    const fallback = baseRecipe(path, tok);
    if (!rule) return fallback;
    if (rule.accent === 'fill')
      return { kind: 'accentFit', use: 'fill', against: [], min: rule.min, toward: null, fallback };
    if (rule.accent === 'text' || rule.accent === 'ring')
      return {
        kind: 'accentFit',
        use: rule.accent,
        against: rule.against,
        min: rule.min,
        toward: theme.colorScheme === 'dark' ? 'white' : 'black',
        fallback,
      };
    if (rule.accent === 'shade')
      return {
        kind: 'accentShade',
        of: rule.of,
        awayFrom: rule.awayFrom,
        amount: rule.amount,
        fallback,
      };
    if (rule.accent === 'foreground') return { kind: 'accentForeground', on: rule.on };
    if (rule.accent) brandErrors.push(`${path}: unknown accent rule ${rule.accent}`);
    if (!['light', 'dark'].includes(rule.from)) brandErrors.push(`${path}: derive needs from`);
    return {
      kind: 'derive',
      from: rule.from,
      toward: rule.toward ?? null,
      amount: rule.amount ?? 0,
      alpha: tok.value.alpha,
    };
  };
  return {
    version: 1,
    ink,
    themes: themes.map((t) => ({
      name: t.name,
      colorScheme: t.colorScheme,
      accent: t.accent,
      roles: Object.fromEntries(
        Object.entries(t.tokens)
          .filter(([p]) => p.startsWith('color.'))
          .map(([p, tok]) => [p.slice('color.'.length), roleRecipe(t, p, tok)]),
      ),
    })),
  };
})();

// Fitted accents must cover every contrast pair they take part in, so that any accent passes.
for (const t of recipe.themes) {
  if (!['light', 'dark'].includes(t.accent))
    brandErrors.push(`${t.name}: theme needs accent: light | dark`);
  for (const [fg, bg, base] of pairs) {
    const required = t.name === 'high-contrast' ? hcBoost(base) : base;
    const r = t.roles[fg];
    if (
      r?.kind === 'accentFit' &&
      r.use !== 'fill' &&
      !(r.against.includes(bg) && r.min >= required)
    )
      brandErrors.push(
        `${t.name} ${fg}: accentFit must fit against ${bg} at ${required}:1 or more`,
      );
    if (
      fg === 'accent-fg' &&
      t.roles['accent-bg']?.kind === 'accentFit' &&
      t.roles['accent-bg'].min < required
    )
      brandErrors.push(`${t.name} accent-bg: fill min must be at least ${required}`);
  }
}

// The Binds pair through the recipe must reproduce what is published: the ink scale and every
// role exactly, except `derive` rules, which the spec allows within 1/255 per channel.
const bindsResolved = resolveBrand(recipe, BINDS);
for (const [step, hex] of Object.entries(inkScale(recipe, BINDS.light, BINDS.dark))) {
  const published = primitives[`color.ink.${step}`].value.hex;
  if (hex !== published)
    brandErrors.push(`color.ink.${step}: computed ${hex} but ${published} is published`);
}
for (const t of recipe.themes) {
  for (const [role, r] of Object.entries(t.roles)) {
    const published = themes.find((x) => x.name === t.name).tokens[`color.${role}`].value;
    const got = bindsResolved.themes[t.name][role];
    const delta = Math.max(
      ...hexToRgb(got.hex).map((c, i) => Math.abs(c - hexToRgb(published.hex)[i])),
    );
    if (got.alpha !== published.alpha || delta > (r.kind === 'derive' ? 1 : 0))
      brandErrors.push(
        `${t.name} ${role}: the Binds pair gives ${got.hex}@${got.alpha} but ${published.hex}@${published.alpha} is published`,
      );
  }
}
if (brandErrors.length) {
  console.error(
    `Brand recipe does not reproduce the published tokens:\n  ${brandErrors.join('\n  ')}`,
  );
  process.exit(1);
}

const contrastTable = pairs.map(([fg, bg, min]) => ({
  fg,
  bg,
  min,
  highContrastMin: hcBoost(min),
}));
/** Failing contrast pairs for resolved themes, in the shape createBrandTheme reports. */
const contrastFailures = (resolved) =>
  recipe.themes.flatMap((t) =>
    contrastTable.flatMap(({ fg, bg, min, highContrastMin }) => {
      const required = t.name === 'high-contrast' ? highContrastMin : min;
      const ratio = contrastRatio(resolved.themes[t.name][fg].hex, resolved.themes[t.name][bg].hex);
      return ratio >= required
        ? []
        : [{ theme: t.name, fg, bg, ratio: Math.round(ratio * 100) / 100, required }];
    }),
  );
const fixture = REFERENCE_BRANDS.map((b) => {
  const resolved = resolveBrand(recipe, b);
  return {
    brand: b,
    ink: resolved.ink,
    themes: resolved.themes,
    contrastFailures: contrastFailures(resolved),
  };
});

// ───────────────────────── helpers ─────────────────────────
const group = (prefix, from = primitives) =>
  Object.entries(from)
    .filter(([p]) => p.startsWith(prefix + '.'))
    .map(([p, t]) => [p.slice(prefix.length + 1), t]);
const num = (n) => String(+n.toFixed(4));
const cssDim = (d) => (d.value === 0 ? '0' : `${num(d.value)}${d.unit}`);
const cssColor = (c) =>
  c.alpha === 1
    ? c.hex
    : `rgba(${c.components.map((x) => Math.round(x * 255)).join(', ')}, ${num(c.alpha)})`;
const cssShadow = (layers) =>
  layers.length === 0
    ? 'none'
    : layers
        .map((l) =>
          [
            cssDim(l.offsetX),
            cssDim(l.offsetY),
            cssDim(l.blur),
            ...(l.spread.value !== 0 ? [cssDim(l.spread)] : []),
            cssColor(l.color),
          ].join(' '),
        )
        .join(', ');
/** Dimension in device-independent units (pt on iOS, dp/sp on Android): rem × 16. */
const points = (d) => (d.unit === 'rem' ? d.value * 16 : d.value);
const camel = (s) =>
  s
    .replace(/[-_.]+([a-zA-Z0-9])/g, (_, c) => c.toUpperCase())
    .replace(/^[A-Z]/, (c) => c.toLowerCase());
const ident = (s) => {
  const c = camel(s);
  return /^[0-9]/.test(c) ? `_${c}` : c;
};
const tsKey = (k) =>
  /^[a-zA-Z_][a-zA-Z0-9_]*$/.test(k) ? k : /^\d+(\.\d+)?$/.test(k) ? k : `'${k}'`;
const origKey = (k) => k.replace(/^(\d+)_(\d+)$/, '$1.$2');

const outputs = {};
/** Kotlin explicit API mode requires a visibility modifier on every declaration. */
const kotlinExplicitApi = (src) =>
  src.replace(/^(\s*)(data class|object|const val|val) /gm, '$1public $2 ');
const emit = (file, content) =>
  (outputs[file] = file.endsWith('.kt') ? kotlinExplicitApi(content) : content);

