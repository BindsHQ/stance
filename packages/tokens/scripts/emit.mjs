// Emits CSS, JSON and framework presets from the compiled token source.
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as t from '../dist/index.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', 'dist');
const P = t.tokenPrefix;
const out = (file, content) => {
  mkdirSync(dirname(join(root, file)), { recursive: true });
  writeFileSync(join(root, file), content);
};
const key = (k) => String(k).replace('.', '-');
const header = '/* Stance design tokens — generated by @bindshq/stance-tokens. Do not edit. */\n';

// ---- scale tokens -------------------------------------------------------
const scales = {
  'color-brand': t.brand,
  'color-ink': t.ink,
  font: t.fontFamily,
  'font-size': t.fontSize,
  'font-weight': t.fontWeight,
  'line-height': t.lineHeight,
  'letter-spacing': t.letterSpacing,
  space: t.space,
  size: t.size,
  radius: t.radius,
  z: t.zIndex,
  breakpoint: t.breakpoint,
  duration: t.duration,
  easing: t.easing,
  'touch-target': t.touchTarget,
  opacity: t.opacity,
};
const scaleDecls = Object.entries(scales)
  .flatMap(([cat, obj]) => Object.entries(obj).map(([k, v]) => `  --${P}-${cat}-${key(k)}: ${v};`))
  .join('\n');

const themeDecls = (theme) =>
  [
    `  color-scheme: ${theme.colorScheme};`,
    ...Object.entries(theme.colors).map(([k, v]) => `  --${P}-color-${k}: ${v};`),
    ...Object.entries(theme.effects).map(([k, v]) => `  --${P}-${k}: ${v};`),
  ].join('\n');

const css = `${header}
:root {
${scaleDecls}
}

:root,
[data-theme='light'] {
${themeDecls(t.light)}
}

[data-theme='dark'] {
${themeDecls(t.dark)}
}

[data-theme='high-contrast'] {
${themeDecls(t.highContrast)}
}

/* No-JS fallbacks: follow the operating system when no theme is set. */
@media (prefers-color-scheme: dark) {
  :root:not([data-theme]) {
${themeDecls(t.dark).replace(/^/gm, '  ')}
  }
}

@media (prefers-contrast: more) {
  :root:not([data-theme]) {
${themeDecls(t.highContrast).replace(/^/gm, '  ')}
  }
}

@media (prefers-reduced-motion: reduce) {
  :root {
    --${P}-duration-fast: 0ms;
    --${P}-duration-normal: 0ms;
    --${P}-duration-slow: 0ms;
  }
}
`;
out('css/tokens.css', css);

// ---- JSON ---------------------------------------------------------------
out(
  'tokens.json',
  JSON.stringify(
    {
      prefix: P,
      scales,
      themes: { light: t.light, dark: t.dark, 'high-contrast': t.highContrast },
    },
    null,
    2,
  ),
);

// ---- Tailwind v3 preset (works with v3 JS configs; no Tailwind dependency) ----
const colorNames = Object.keys(t.light.colors);
const tw = (name) =>
  `color-mix(in srgb, var(--${P}-color-${name}) calc(<alpha-value> * 100%), transparent)`;
const twColors = Object.fromEntries(colorNames.map((n) => [n, tw(n)]));
twColors.ivory = tw('brand-ivory');
twColors.indigo = tw('brand-indigo');
twColors.ink = Object.fromEntries(Object.keys(t.ink).map((k) => [k, tw(`ink-${k}`)]));
const fromScale = (cat, obj) =>
  Object.fromEntries(Object.keys(obj).map((k) => [key(k), `var(--${P}-${cat}-${key(k)})`]));
const preset = {
  darkMode: 'class',
  theme: {
    extend: {
      colors: { stance: twColors },
      fontFamily: { stance: [`var(--${P}-font-sans)`], 'stance-mono': [`var(--${P}-font-mono)`] },
      fontSize: Object.fromEntries(
        Object.keys(t.fontSize).map((k) => [`stance-${k}`, `var(--${P}-font-size-${k})`]),
      ),
      borderRadius: Object.fromEntries(
        Object.keys(t.radius).map((k) => [`stance-${k}`, `var(--${P}-radius-${k})`]),
      ),
      boxShadow: Object.fromEntries(
        ['xs', 'sm', 'md', 'lg', 'xl'].map((k) => [`stance-${k}`, `var(--${P}-shadow-${k})`]),
      ),
      zIndex: Object.fromEntries(
        Object.keys(t.zIndex).map((k) => [`stance-${k}`, `var(--${P}-z-${k})`]),
      ),
      transitionDuration: Object.fromEntries(
        Object.keys(t.duration).map((k) => [`stance-${k}`, `var(--${P}-duration-${k})`]),
      ),
      spacing: Object.fromEntries(
        Object.entries(fromScale('space', t.space)).map(([k, v]) => [`stance-${k}`, v]),
      ),
    },
  },
};
const presetJson = JSON.stringify(preset, null, 2);
out(
  'tailwind.js',
  `// Tailwind CSS v3 preset for Stance. Usage: presets: [stancePreset]\nconst preset = ${presetJson};\nexport default preset;\n`,
);
out(
  'tailwind.d.ts',
  `declare const preset: { darkMode: 'class'; theme: { extend: Record<string, any> } };\nexport default preset;\n`,
);

// ---- Tailwind v4 theme --------------------------------------------------
const v4 = [
  ...colorNames.map((n) => `  --color-stance-${n}: var(--${P}-color-${n});`),
  `  --color-stance-ivory: var(--${P}-color-brand-ivory);`,
  `  --color-stance-indigo: var(--${P}-color-brand-indigo);`,
  `  --font-stance: var(--${P}-font-sans);`,
  ...Object.keys(t.radius).map((k) => `  --radius-stance-${k}: var(--${P}-radius-${k});`),
  ...['xs', 'sm', 'md', 'lg', 'xl'].map((k) => `  --shadow-stance-${k}: var(--${P}-shadow-${k});`),
].join('\n');
out('css/tailwind-v4.css', `${header}@theme inline {\n${v4}\n}\n`);

// ---- contrast report -----------------------------------------------------
out(
  'contrast-report.json',
  JSON.stringify((await import('./contrast-pairs.mjs')).report(t), null, 2),
);
console.log('tokens emitted →', root);
